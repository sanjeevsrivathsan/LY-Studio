/* codegen.c - 8086 (MASM/TASM/emu8086 style) code generator from three address code */
#include <string.h>
#include <stdlib.h>
#include "mincc.h"

static int  rel_count = 0;
static int  used(const char *s) {
    for (int i = 0; i < nq; i++)
        if (!strcmp(quad[i].a1, s) || !strcmp(quad[i].a2, s) || !strcmp(quad[i].res, s)) return 1;
    return 0;
}
static void ldax(FILE *f, const char *x) { fprintf(f, "    MOV  AX, %s\n", x); }

int gen_8086(FILE *f, const char *srcname) {
    for (int i = 0; i < nsym; i++)
        if (!symtab[i].is_temp && symtab[i].type == T_FLOAT) {
            fprintf(f, "back-end: '%s' is float - the integer 8086 back-end cannot compile it\n", symtab[i].name);
            return 1;
        }
    fprintf(f, "; ------------------------------------------------------------\n");
    fprintf(f, "; 8086 assembly generated by MiniCC from %s\n", srcname);
    fprintf(f, "; ------------------------------------------------------------\n");
    fprintf(f, ".MODEL SMALL\n.STACK 100H\n.DATA\n");
    for (int i = 0; i < nsym; i++)
        if (used(symtab[i].name) || !symtab[i].is_temp)
            fprintf(f, "    %-6s DW 0\n", symtab[i].name);
    fprintf(f, ".CODE\nMAIN PROC\n    MOV  AX, @DATA\n    MOV  DS, AX\n");

    char tac[160];
    for (int i = 0; i < nq; i++) {
        Quad *q = &quad[i];
        const char *op = q->op;
        fmt_quad(q, tac);
        if (!strcmp(op, "label")) { fprintf(f, "%s:\n", q->res); continue; }
        fprintf(f, "    ; %s\n", tac);
        if (!strcmp(op, "=")) {
            ldax(f, q->a1); fprintf(f, "    MOV  %s, AX\n", q->res);
        } else if (!strcmp(op, "neg")) {
            ldax(f, q->a1); fprintf(f, "    NEG  AX\n    MOV  %s, AX\n", q->res);
        } else if (!strcmp(op, "+") || !strcmp(op, "-")) {
            ldax(f, q->a1);
            fprintf(f, "    %s  AX, %s\n    MOV  %s, AX\n", op[0] == '+' ? "ADD" : "SUB", q->a2, q->res);
        } else if (!strcmp(op, "*")) {
            ldax(f, q->a1);
            fprintf(f, "    MOV  BX, %s\n    IMUL BX\n    MOV  %s, AX\n", q->a2, q->res);
        } else if (!strcmp(op, "/")) {
            ldax(f, q->a1);
            fprintf(f, "    CWD\n    MOV  BX, %s\n    IDIV BX\n    MOV  %s, AX\n", q->a2, q->res);
        } else if (!strcmp(op, "<<")) {
            ldax(f, q->a1);
            fprintf(f, "    MOV  CL, %s\n    SHL  AX, CL\n    MOV  %s, AX\n", q->a2, q->res);
        } else if (!strcmp(op, "<") || !strcmp(op, ">") || !strcmp(op, "<=") ||
                   !strcmp(op, ">=") || !strcmp(op, "==") || !strcmp(op, "!=")) {
            const char *j = !strcmp(op,"<") ? "JL" : !strcmp(op,">") ? "JG" : !strcmp(op,"<=") ? "JLE" :
                            !strcmp(op,">=") ? "JGE" : !strcmp(op,"==") ? "JE" : "JNE";
            int n = ++rel_count;
            ldax(f, q->a1);
            fprintf(f, "    CMP  AX, %s\n    %-4s CT%d\n    MOV  %s, 0\n    JMP  CE%d\nCT%d:\n    MOV  %s, 1\nCE%d:\n",
                    q->a2, j, n, q->res, n, n, q->res, n);
        } else if (!strcmp(op, "iffalse")) {
            int n = ++rel_count;
            ldax(f, q->a1);
            fprintf(f, "    CMP  AX, 0\n    JNE  CT%d\n    JMP  %s\nCT%d:\n", n, q->res, n);
        } else if (!strcmp(op, "goto")) {
            fprintf(f, "    JMP  %s\n", q->res);
        } else if (!strcmp(op, "print")) {
            ldax(f, q->a1); fprintf(f, "    CALL PRINT_NUM\n");
        }
    }
    fprintf(f, "    MOV  AH, 4CH\n    INT  21H\nMAIN ENDP\n\n");
    fprintf(f,
"; ---- prints the signed integer in AX followed by CR/LF ----\n"
"PRINT_NUM PROC\n    PUSH AX\n    PUSH BX\n    PUSH CX\n    PUSH DX\n"
"    CMP  AX, 0\n    JGE  PN_POS\n    PUSH AX\n    MOV  DL, '-'\n    MOV  AH, 02H\n    INT  21H\n    POP  AX\n    NEG  AX\n"
"PN_POS:\n    MOV  CX, 0\n    MOV  BX, 10\n"
"PN_DIV:\n    MOV  DX, 0\n    DIV  BX\n    PUSH DX\n    INC  CX\n    CMP  AX, 0\n    JNE  PN_DIV\n"
"PN_OUT:\n    POP  DX\n    ADD  DL, '0'\n    MOV  AH, 02H\n    INT  21H\n    LOOP PN_OUT\n"
"    MOV  DL, 0DH\n    MOV  AH, 02H\n    INT  21H\n    MOV  DL, 0AH\n    MOV  AH, 02H\n    INT  21H\n"
"    POP  DX\n    POP  CX\n    POP  BX\n    POP  AX\n    RET\nPRINT_NUM ENDP\nEND MAIN\n");
    return 0;
}
